"""Generate native C++ for [hle_hooks] float leaf functions from the game's code.

    gen_natives.py <recompiled project dir> <out.cpp> <native name>...

The recompiler keeps a hooked function's original instructions as
"// 0xADDR: WORD" comments in the stub that calls the hook, e.g.
"gs8e_mtx44_scale(ctx);". For each native name this finds that stub,
symbolically executes the straight-line PowerPC float code and emits a C++
function doing the same float operations in the same order, with the
recompiler's rounding (single ops = (float)(double op), fmadds =
(float)std::fma(a, c, b)), so results are bit-identical. All loads happen
before the first store, as in the original, so destinations may alias
sources. Fails loudly on any instruction it does not model.

The output is derived from the game's code: build.ps1 writes it into the
generated project (export/natives/), never into the repository.
"""
import glob
import os
import re
import sys

HEADER = '''\
// Native versions of game functions bound through [hle_hooks], generated by
// tools/gen_natives.py from the game's own code at build time (do not edit,
// do not commit). Each is the original straight-line float code with the same
// operations in the same order, so results are bit-identical; a fast path
// reads guest RAM directly when the pointers cover plain MEM1.

#include "runtime/cpu_context.h"

#include <cmath>
#include <cstring>

using nwii::runtime::CPUContext;
using nwii::runtime::nwii_bswap32;

namespace {

// [p, p + 64) lies in plain MEM1 (see MMU::fast_ram).
inline bool ram64(uint32_t p) { return nwii::runtime::MMU::fast_ram(p & 0x3FFFFFFF, 64); }

// Big-endian float load/store at a MEM1 offset (the fast path of
// MMU::read_f32 / write_f32 without the per-access range check).
inline float ld(const uint8_t *m, uint32_t o) {
  uint32_t v;
  std::memcpy(&v, m + o, 4);
  v = nwii_bswap32(v);
  float f;
  std::memcpy(&f, &v, 4);
  return f;
}
inline void st(uint8_t *m, uint32_t o, float f) {
  uint32_t v;
  std::memcpy(&v, &f, 4);
  v = nwii_bswap32(v);
  std::memcpy(m + o, &v, 4);
}

} // namespace

extern "C" {
'''


def find_stub(project, native):
    """(function name, [(addr, word)]) of the stub that calls `native`."""
    call = re.compile(r'^void (func_[0-9A-F]{8})\(CPUContext&[^)]*\) \{\n    %s\(ctx\);\n' % re.escape(native), re.M)
    for path in sorted(glob.glob(os.path.join(project, 'output_*.cpp'))):
        txt = open(path, encoding='utf-8', errors='replace').read()
        m = call.search(txt)
        if m:
            end = txt.index('\n}\n', m.start())
            ins = [(int(a, 16), int(w, 16))
                   for a, w in re.findall(r'// 0x([0-9A-F]{8}): ([0-9A-F]{8})', txt[m.start():end])]
            if not ins:
                raise SystemExit('%s: stub %s has no instruction comments (recompiler too old?)' % (native, m.group(1)))
            return m.group(1), ins
    raise SystemExit('%s: no [hle_hooks] stub calls it in %s' % (native, project))


def generate(native, fn, ins):
    fr = {k: 'ctx.fpr[%d]' % k for k in range(32)}  # expression (a C++ temp name) per FPR
    spill = {}   # stack offset -> expression
    out = []     # C++ statements
    loads = {}   # (reg, off) -> temp
    ptr = {3: 'p3', 4: 'p4', 5: 'p5', 6: 'p6'}
    state = {'stores': False, 'ntemp': 0}

    def temp(expr):
        n = 't%d' % state['ntemp']
        state['ntemp'] += 1
        out.append('  const double %s = %s;' % (n, expr))
        return n

    for a, w in ins:
        op = w >> 26; rD = (w >> 21) & 31; rA = (w >> 16) & 31; rB = (w >> 11) & 31; rC = (w >> 6) & 31
        d = w & 0xFFFF
        if d & 0x8000: d -= 0x10000
        xo5 = (w >> 1) & 0x1F
        if op == 37 and rD == 1 and rA == 1: continue            # stwu r1
        if op == 14 and rD == 1 and rA == 1: continue            # addi r1
        if op in (60, 56, 61, 57) and rA == 1: continue          # psq_st/psq_l callee saves
        if op == 54 and rA == 1: spill[d] = fr[rD]; continue     # stfd spill
        if op == 50 and rA == 1:                                  # lfd reload
            fr[rD] = spill.get(d, 'ctx.fpr[%d]' % rD)            # or callee-save restore
            continue
        if op == 19 and ((w >> 1) & 0x3FF) == 16 and rD == 20: break   # blr
        if op == 48:                                              # lfs
            assert rA in ptr, '%s: lfs base r%d at %08X' % (native, rA, a)
            assert not state['stores'], '%s: load after store at %08X' % (native, a)
            key = (rA, d)
            if key not in loads:
                loads[key] = temp('(double)ctx.mmu.read_f32(%s + %d)' % (ptr[rA], d))
            fr[rD] = loads[key]; continue
        if op == 52:                                              # stfs
            assert rA in ptr, '%s: stfs base r%d at %08X' % (native, rA, a)
            state['stores'] = True
            out.append('  ctx.mmu.write_f32(%s + %d, (float)%s);' % (ptr[rA], d, fr[rD])); continue
        if op == 59:
            if xo5 == 25: fr[rD] = temp('(double)(float)(%s * %s)' % (fr[rA], fr[rC])); continue
            if xo5 == 21: fr[rD] = temp('(double)(float)(%s + %s)' % (fr[rA], fr[rB])); continue
            if xo5 == 20: fr[rD] = temp('(double)(float)(%s - %s)' % (fr[rA], fr[rB])); continue
            if xo5 == 29: fr[rD] = temp('(double)(float)std::fma(%s, %s, %s)' % (fr[rA], fr[rC], fr[rB])); continue
            if xo5 == 28: fr[rD] = temp('(double)(float)std::fma(%s, %s, -%s)' % (fr[rA], fr[rC], fr[rB])); continue
        if op == 63 and ((w >> 1) & 0x3FF) == 72: fr[rD] = fr[rB]; continue   # fmr
        raise SystemExit('%s: unhandled instruction %08X at %08X (op %d xo %d)' % (native, w, a, op, xo5))

    regs = sorted({k[0] for k in loads} | {3})
    body = '\n'.join(out)
    lines = ['// 0x%08X (%s).' % (ins[0][0], fn), 'void %s(CPUContext &ctx) {' % native]
    lines += ['  const uint32_t p%d = ctx.gpr[%d];' % (r, r) for r in regs]
    # Fast path: every pointer covers 64 bytes of plain MEM1 and nothing is watched.
    lines.append('  if (!nwii::runtime::g_watch_addr && %s) {' % ' && '.join('ram64(p%d)' % r for r in regs))
    lines.append('    uint8_t *const m = ctx.mmu.mem1.data();')
    lines += ['    const uint32_t o%d = p%d & 0x3FFFFFFF;' % (r, r) for r in regs]
    fast = re.sub(r'ctx\.mmu\.read_f32\(p(\d) \+ (-?\d+)\)', r'ld(m, o\1 + \2)', body)
    fast = re.sub(r'ctx\.mmu\.write_f32\(p(\d) \+ (-?\d+), ', r'st(m, o\1 + \2, ', fast)
    lines += ['  ' + l for l in fast.split('\n')]
    lines += ['    return;', '  }', body, '}']
    return '\n'.join(lines)


def main():
    if len(sys.argv) < 4:
        raise SystemExit(__doc__)
    project, out_path, natives = sys.argv[1], sys.argv[2], sys.argv[3:]
    parts = [HEADER]
    for native in natives:
        fn, ins = find_stub(project, native)
        parts.append(generate(native, fn, ins) + '\n')
    parts.append('} // extern "C"\n')
    text = '\n'.join(parts)
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    with open(out_path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('%s: %d natives' % (out_path, len(natives)))


if __name__ == '__main__':
    main()
